// WriteJSON writes results to path.
func WriteJSON(path string, results []scenario.Result) error {
	data, err := json.MarshalIndent(results, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, data, 0o644)
}

// WriteMarkdown writes a wiki-shaped markdown report grouped by section.
func WriteMarkdown(path string, results []scenario.Result) error {
	var b strings.Builder
	b.WriteString("# KubeArmor Performance Benchmarking Data\n\n")
	b.WriteString("Generated by kbc.\n\n")

	sections := orderedSections(results)
	for _, section := range sections {
		b.WriteString("## " + section + "\n\n")
		b.WriteString("| Scenario | Users | Kubearmor CPU (m) | Kubearmor Memory (Mi) | Throughput (req/s) | Failed Requests | Kubearmor Relay CPU (m) | Kubearmor Relay Memory | Percentage Drop | Micro-service CPU (Frontend) | Micro-service CPU (CartService) | Micro-service CPU (CurrencyService) | Notes |\n")
		b.WriteString("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |\n")
		for _, r := range results {
			if r.Section != section {
				continue
			}
			if r.Skipped {
				fmt.Fprintf(&b, "| %s | %d | - | - | - | - | - | - | - | - | - | - | SKIPPED: %s |\n",
					r.Description, r.Users, r.SkipReason)
				continue
			}
			m := r.Aggregate.Mean
			fmt.Fprintf(&b,
				"| %s | %d | %.2f | %.2f | %.2f | %.0f | %.2f | %.2f | %.2f | %.2fm (%d replica) | %.2fm (%d replica) | %.2fm (%d replica) | |\n",
				r.Description, r.Users,
				m.KubeArmorCPU, m.KubeArmorMemory,
				m.Throughput, m.FailedRequests,
				m.RelayCPU, m.RelayMemory,
				r.PercentageDrop,
				m.FrontendCPU, int(m.FrontendReplicas+0.5),
				m.CartCPU, int(m.CartReplicas+0.5),
				m.CurrencyCPU, int(m.CurrencyReplicas+0.5),
			)
		}
		b.WriteString("\n")
	}
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func orderedSections(results []scenario.Result) []string {
	seen := map[string]bool{}
	var out []string
	for _, r := range results {
		if !seen[r.Section] {
			seen[r.Section] = true
			out = append(out, r.Section)
		}
	}
	return out
}

// ExecuteTemplate is available for custom templates.
func ExecuteTemplate(templatePath, outPath string, data any) error {
	content, err := os.ReadFile(templatePath)
	if err != nil {
		return err
	}
	tmpl, err := template.New("report").Parse(string(content))
	if err != nil {
		return err
	}
	f, err := os.Create(outPath)
	if err != nil {
		return err
	}
	defer f.Close()
	return tmpl.Execute(f, data)
}
